-- My Laptop Activity Monitor - SQLite schema. All timestamps are Unix epoch seconds (UTC, REAL).
CREATE TABLE IF NOT EXISTS app_sessions (
  id        INTEGER PRIMARY KEY AUTOINCREMENT,
  app       TEXT NOT NULL,           -- friendly name, e.g. "Google Chrome"
  exe       TEXT NOT NULL,           -- executable, e.g. "chrome.exe"
  start_ts  REAL NOT NULL,
  end_ts    REAL NOT NULL,
  duration  REAL NOT NULL DEFAULT 0, -- seconds of active foreground use
  title     TEXT                     -- window title, ONLY if track_window_titles is enabled (off by default)
);
CREATE INDEX IF NOT EXISTS ix_app_time ON app_sessions(start_ts, end_ts);
CREATE INDEX IF NOT EXISTS ix_app_exe ON app_sessions(exe);

CREATE TABLE IF NOT EXISTS state_sessions (
  id        INTEGER PRIMARY KEY AUTOINCREMENT,
  state     TEXT NOT NULL,           -- 'active' | 'idle' | 'locked'
  start_ts  REAL NOT NULL,
  end_ts    REAL NOT NULL,
  duration  REAL NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_state_time ON state_sessions(start_ts, end_ts);

CREATE TABLE IF NOT EXISTS system_samples (
  ts REAL NOT NULL, cpu_pct REAL, ram_pct REAL, ram_used INTEGER, ram_total INTEGER, proc_count INTEGER
);
CREATE INDEX IF NOT EXISTS ix_sys_ts ON system_samples(ts);

CREATE TABLE IF NOT EXISTS process_samples (
  ts REAL NOT NULL, name TEXT NOT NULL, cpu_pct REAL, rss INTEGER, instances INTEGER, foreground INTEGER
);
CREATE INDEX IF NOT EXISTS ix_proc_ts ON process_samples(ts);
CREATE INDEX IF NOT EXISTS ix_proc_name ON process_samples(name, ts);

CREATE TABLE IF NOT EXISTS battery_samples (
  ts REAL NOT NULL, percent REAL, plugged INTEGER, secs_left INTEGER,
  charge_rate_mw INTEGER, discharge_rate_mw INTEGER, remaining_mwh INTEGER
);
CREATE INDEX IF NOT EXISTS ix_batt_ts ON battery_samples(ts);

CREATE TABLE IF NOT EXISTS app_categories (exe TEXT PRIMARY KEY COLLATE NOCASE, category TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS kv (key TEXT PRIMARY KEY, value TEXT, updated REAL);  -- live state (current processes, heartbeat...)
CREATE TABLE IF NOT EXISTS events (ts REAL NOT NULL, kind TEXT NOT NULL, detail TEXT);

-- ---------------------------------------------------------------- v2: Chrome website tracking (additive migration)
-- One row per Chrome extension installation (= one Chrome profile).
CREATE TABLE IF NOT EXISTS chrome_profiles (
  profile_id  TEXT PRIMARY KEY,          -- random UUID generated by the extension in that profile
  secret_hash TEXT NOT NULL,             -- SHA-256 of the per-install secret (trust on first use)
  label       TEXT,                      -- NULL = Unconfigured
  label_ts    REAL DEFAULT 0,            -- last label change (newest wins: extension options vs dashboard)
  enabled     INTEGER NOT NULL DEFAULT 1,
  ext_version TEXT,
  first_seen  REAL NOT NULL,
  last_seen   REAL NOT NULL,             -- last contact from the extension
  last_activity REAL                     -- end of newest website session
);

-- One row per continuous active use of one domain. Domain only: never URL, path or query.
CREATE TABLE IF NOT EXISTS web_sessions (
  id          TEXT PRIMARY KEY,          -- UUID from the extension: re-sending a segment updates it (no double counting)
  profile_id  TEXT NOT NULL,
  profile_label TEXT,                    -- label at time of recording
  browser     TEXT NOT NULL DEFAULT 'chrome',
  domain      TEXT NOT NULL,
  start_ts    REAL NOT NULL,
  end_ts      REAL NOT NULL,
  duration    REAL NOT NULL,
  day         TEXT NOT NULL,             -- local YYYY-MM-DD of start
  end_reason  TEXT                       -- tab_switch | blur | idle | locked | closed | ...
);
CREATE INDEX IF NOT EXISTS ix_web_time ON web_sessions(start_ts, end_ts);
CREATE INDEX IF NOT EXISTS ix_web_profile_day ON web_sessions(profile_id, day);
CREATE INDEX IF NOT EXISTS ix_web_domain ON web_sessions(domain);

-- Your overrides for website category and productivity class.
CREATE TABLE IF NOT EXISTS web_domains (
  domain       TEXT PRIMARY KEY COLLATE NOCASE,
  category     TEXT,                     -- Education | Development | Social Media | Entertainment | Productivity | Other
  productivity TEXT                      -- Productive | Neutral | Distracting
);
